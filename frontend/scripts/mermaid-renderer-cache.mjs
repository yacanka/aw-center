import { createHash, randomUUID } from 'node:crypto'
import { mkdir, readFile, readdir, realpath, rename, rm, stat, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, extname, isAbsolute, join, relative, resolve } from 'node:path'
import { Script } from 'node:vm'
import ts from 'typescript'

const digest = (source) => createHash('sha256').update(source).digest('hex')

export function validateRenderer(source) {
  if (
    typeof source !== 'string' ||
    !source.trim() ||
    /\bimport(?:\s|\/\*[\s\S]*?\*\/|\/\/[^\n]*\n)*\(/.test(source)
  )
    throw new Error('Mermaid renderer must be a single self-contained classic script.')
  try {
    new Script(source)
  } catch {
    throw new Error('Mermaid renderer must be a single self-contained classic script.')
  }
}

/** Each rename replaces a whole file; a receipt may authorize only its own generated bytes. */
export async function publishRenderer(source, directory) {
  await mkdir(directory, { recursive: true })
  const temporary = join(directory, `renderer-${randomUUID()}.tmp`)
  try {
    await writeFile(temporary, source, { flag: 'wx' })
    await rename(temporary, join(directory, 'renderer.js'))
  } finally {
    await rm(temporary, { force: true })
  }
}

async function inputFingerprint({ rootDirectory, entry, scriptFiles, buildOptions, nodeVersion }) {
  const files = new Set(scriptFiles)
  const rendererDirectory = dirname(entry)
  // Include the renderer's file set, even files not imported by the current entry.
  async function inventory(directory) {
    for (const item of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, item.name)
      if (item.isDirectory()) await inventory(path)
      else files.add(path)
    }
  }
  await inventory(rendererDirectory)
  files.add(join(rootDirectory, 'package-lock.json'))
  const configPath = join(rootDirectory, 'tsconfig.json')
  files.add(configPath)
  const config = ts.readConfigFile(configPath, ts.sys.readFile)
  if (config.error) throw new Error('Cannot read renderer TypeScript configuration.')
  const parsed = ts.parseJsonConfigFileContent(
    config.config,
    {
      ...ts.sys,
      // Only compiler options are needed; do not inventory the application's source tree.
      readDirectory: () => [],
      readFile(path) {
        files.add(resolve(path))
        return ts.sys.readFile(path)
      }
    },
    rootDirectory
  )
  const visited = new Set()
  const candidates = new Set()
  const isInstalled = (path) => /[\\/]node_modules[\\/]/.test(path)
  const scriptExtensions = /\.(?:[cm]?[jt]s|[jt]sx)$/
  // TypeScript can select .ts/.d.ts while Vite builds .js/.mjs instead. Track the
  // bounded candidate set rather than treating TypeScript's target as runtime truth.
  const extensions = [
    '.mjs',
    '.js',
    '.mts',
    '.ts',
    '.jsx',
    '.tsx',
    '.json',
    '.cjs',
    '.cts',
    '.d.ts'
  ]
  async function candidate(path) {
    if (candidates.has(path)) return
    candidates.add(path)
    if (isInstalled(path)) return
    let info
    try {
      info = await stat(path)
      if (isInstalled(await realpath(path))) return
    } catch (error) {
      if (error.code === 'ENOENT' || error.code === 'ENOTDIR') return
      throw error
    }
    if (info.isDirectory()) {
      // Local directory imports may use package entry fields rather than index.ts.
      // Inventory only that imported directory, never a containing source/dependency tree.
      for (const item of await readdir(path)) await candidate(join(path, item))
    } else if (info.isFile()) {
      files.add(path)
      if (scriptExtensions.test(path)) await imports(path)
      else if (path.endsWith('package.json')) {
        const manifest = JSON.parse(await readFile(path, 'utf8'))
        async function packageTargets(value) {
          if (typeof value === 'string' && !value.includes('*'))
            await resolutionCandidates(resolve(dirname(path), value))
          else if (value && typeof value === 'object')
            for (const nested of Object.values(value)) await packageTargets(nested)
        }
        for (const field of [
          'main',
          'module',
          'browser',
          'exports',
          'types',
          'typings',
          'jsnext:main',
          'jsnext'
        ])
          await packageTargets(manifest[field])
      }
    }
  }
  async function resolutionCandidates(path) {
    const extension = extname(path)
    const stem = extensions.includes(extension) ? path.slice(0, -extension.length) : path
    for (const possible of new Set([path, stem, ...extensions.map((suffix) => stem + suffix)]))
      await candidate(possible)
  }
  async function imports(path) {
    if (visited.has(path)) return
    visited.add(path)
    files.add(path)
    const source = await readFile(path, 'utf8')
    for (const imported of ts.preProcessFile(source, true, true).importedFiles) {
      const module = ts.resolveModuleName(
        imported.fileName,
        path,
        parsed.options,
        ts.sys
      ).resolvedModule
      const specifier = imported.fileName.split(/[?#]/, 1)[0]
      if (specifier.startsWith('.') || isAbsolute(specifier))
        await resolutionCandidates(resolve(dirname(path), specifier))
      // Installed packages remain identified by lock/tool metadata, never traversed.
      if (module && !module.isExternalLibraryImport && !isInstalled(module.resolvedFileName))
        await resolutionCandidates(resolve(module.resolvedFileName))
      // Missing conservative alternatives are allowed; Vite validates the actual runtime graph.
    }
  }
  await imports(entry)
  const require = createRequire(join(rootDirectory, 'package.json'))
  const vitePackage = require.resolve('vite/package.json')
  const viteRequire = createRequire(vitePackage)
  const tools = [
    vitePackage,
    viteRequire.resolve('rolldown/package.json'),
    require.resolve('typescript/package.json')
  ]
  for (const path of tools) files.add(path)
  const identities = await Promise.all(
    [...files]
      .sort()
      .map(async (path) => [relative(rootDirectory, path), digest(await readFile(path))])
  )
  return digest(
    JSON.stringify(
      {
        schema: 1,
        nodeVersion,
        nodeExecutable: process.execPath,
        platform: process.platform,
        architecture: process.arch,
        buildOptions,
        identities
      },
      (_key, value) => (typeof value === 'function' ? value.toString() : value)
    )
  )
}

async function reusableOutput(directory, inputDigest) {
  try {
    const receipt = JSON.parse(await readFile(join(directory, 'receipt.json'), 'utf8'))
    if (receipt.schema !== 1 || receipt.inputDigest !== inputDigest) return false
    const source = await readFile(join(directory, 'renderer.js'), 'utf8')
    if (receipt.outputDigest !== digest(source)) return false
    validateRenderer(source)
    return true
  } catch {
    return false
  }
}

export async function prepareCachedRenderer(options) {
  const { outputDirectory, dev, force, buildOperation, signal, log } = options
  signal?.throwIfAborted()
  // Vite normalizes its options in place; fingerprint the request, not its mutable work object.
  const fingerprintOptions = {
    ...options,
    buildOptions: JSON.stringify(options.buildOptions, (_key, value) =>
      typeof value === 'function' ? value.toString() : value
    )
  }
  const inputDigest = await inputFingerprint(fingerprintOptions)
  if (dev && !force && (await reusableOutput(outputDirectory, inputDigest))) {
    signal?.throwIfAborted()
    // The filesystem may have changed while the output was being checked.
    if ((await inputFingerprint(fingerprintOptions)) === inputDigest) {
      log('Isolated Mermaid renderer reused from verified development cache.')
      return 'reused'
    }
    throw new Error('Mermaid renderer inputs changed during cache validation; retry preparation.')
  }
  const source = await buildOperation(options.buildOptions)
  signal?.throwIfAborted()
  validateRenderer(source)
  // Compute from this build's bytes, never from renderer.js (another build may replace it).
  const receipt = JSON.stringify({ schema: 1, inputDigest, outputDigest: digest(source) }) + '\n'
  await mkdir(outputDirectory, { recursive: true })
  const temporaryOutput = join(outputDirectory, `renderer-${randomUUID()}.tmp`)
  const temporaryReceipt = join(outputDirectory, `receipt-${randomUUID()}.tmp`)
  try {
    await writeFile(temporaryOutput, source, { flag: 'wx' })
    await writeFile(temporaryReceipt, receipt, { flag: 'wx' })
    if ((await inputFingerprint(fingerprintOptions)) !== inputDigest)
      throw new Error('Mermaid renderer inputs changed during build; retry preparation.')
    signal?.throwIfAborted()
    await rename(temporaryOutput, join(outputDirectory, 'renderer.js'))
    if ((await inputFingerprint(fingerprintOptions)) !== inputDigest)
      throw new Error('Mermaid renderer inputs changed during publication; retry preparation.')
    signal?.throwIfAborted()
    // A mismatched output/receipt pair after interruption or concurrent publication is a cache miss.
    await rename(temporaryReceipt, join(outputDirectory, 'receipt.json'))
  } finally {
    await Promise.all([temporaryOutput, temporaryReceipt].map((path) => rm(path, { force: true })))
  }
  log('Isolated Mermaid renderer built with no runtime imports.')
  return 'built'
}
